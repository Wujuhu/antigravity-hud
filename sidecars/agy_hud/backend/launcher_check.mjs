/**
 * Cross-platform CDP launcher existence probe & on-demand auto-repair reconciler.
 *
 * When CDP injection is abnormal (e.g. user launched Antigravity via the official
 * icon or deleted the HUD launcher):
 *   - If the HUD launcher still exists on disk: do NOT regenerate it; return its
 *     full path with status `'existing'`.
 *   - If the HUD launcher was deleted/missing: regenerate it once automatically
 *     and return its full path with status `'auto_regenerated'`.
 */

import fs from 'node:fs';
import { DEFAULT_CDP_PORT } from './config.mjs';
import {
  detectWindowsCdpLauncher,
  generateWindowsCdpLauncher,
} from './launcher_win.mjs';
import {
  detectMacCdpLauncher,
  generateMacCdpLauncher,
} from './launcher_mac.mjs';

const FAILURE_COOLDOWN_MS = 30_000;

export function detectPlatformLauncher({
  platform = process.platform,
  dataDir = '',
  desktopDir,
  applicationsDir = '',
  port = DEFAULT_CDP_PORT,
} = {}) {
  const p = Number(port) || DEFAULT_CDP_PORT;
  if (platform === 'win32') {
    return detectWindowsCdpLauncher({ dataDir, desktopDir, port: p });
  }
  if (platform === 'darwin') {
    return detectMacCdpLauncher({ applicationsDir, desktopDir, port: p });
  }
  return {
    platform,
    port: p,
    exists: false,
    manualOnly: true,
    launcherPath: '',
    manualCommand: `antigravity --remote-debugging-port=${p}`,
  };
}

export async function generatePlatformLauncherForOs({
  platform = process.platform,
  dataDir = '',
  desktopDir,
  applicationsDir = '',
  port = DEFAULT_CDP_PORT,
} = {}) {
  const p = Number(port) || DEFAULT_CDP_PORT;
  if (platform === 'win32') {
    return generateWindowsCdpLauncher({ dataDir, desktopDir, port: p });
  }
  if (platform === 'darwin') {
    return generateMacCdpLauncher({ applicationsDir, desktopDir, port: p });
  }
  return {
    platform,
    port: p,
    manualOnly: true,
    manualCommand: `antigravity --remote-debugging-port=${p}`,
  };
}

function extractPrimaryLauncherPath(info) {
  if (!info || typeof info !== 'object') return '';
  return info.lnkPath || info.bundlePath || info.launcherPath || info.cmdPath || '';
}

export function createLauncherReconciler({
  platform = process.platform,
  dataDir = '',
  desktopDir,
  applicationsDir = '',
  detectImpl = detectPlatformLauncher,
  generateImpl = generatePlatformLauncherForOs,
  now = () => Date.now(),
} = {}) {
  let outageEpoch = 0;
  let autoRegeneratedInOutage = false;
  let generatedFallbackPath = '';
  let lastGeneratedInfo = null;
  let lastFailureAtMs = 0;
  let lastError = '';
  let inFlight = null;
  let inFlightPort = null;

  function makeStatus(status, extra = {}) {
    return {
      status,
      autoGenerated: false,
      launcherPath: '',
      desktopShortcutPath: '',
      manualCommand: '',
      error: '',
      ...extra,
    };
  }

  async function runGenerate(port, reasonStatus = 'auto_regenerated') {
    if (inFlight && inFlightPort === port) return inFlight;
    const myEpoch = outageEpoch;
    inFlightPort = port;
    inFlight = (async () => {
      try {
        const info = await generateImpl({
          platform,
          dataDir,
          desktopDir,
          applicationsDir,
          port,
        });
        const launcherPath = extractPrimaryLauncherPath(info);
        lastGeneratedInfo = info;
        if (!launcherPath) {
          lastFailureAtMs = now();
          lastError = '未能生成可用的启动器文件';
          return {
            ...makeStatus('generate_failed', {
              manualCommand: info?.manualCommand || '',
              error: lastError,
            }),
            info,
          };
        }
        lastFailureAtMs = 0;
        lastError = '';
        if (myEpoch === outageEpoch) {
          autoRegeneratedInOutage = true;
          generatedFallbackPath = launcherPath;
        }
        return {
          ...makeStatus(reasonStatus, {
            autoGenerated: reasonStatus === 'auto_regenerated',
            launcherPath,
            desktopShortcutPath: info?.desktopShortcutPath || '',
            manualCommand: info?.manualCommand || '',
          }),
          info,
        };
      } catch (err) {
        lastFailureAtMs = now();
        lastError = err instanceof Error ? err.message : String(err);
        return {
          ...makeStatus('generate_failed', { error: lastError }),
          info: null,
        };
      } finally {
        inFlight = null;
        inFlightPort = null;
      }
    })();
    return inFlight;
  }

  async function reconcile({ connected = false, cdpEnabled = true, port = DEFAULT_CDP_PORT } = {}) {
    const p = Number(port) || DEFAULT_CDP_PORT;

    if (connected) {
      outageEpoch += 1;
      autoRegeneratedInOutage = false;
      generatedFallbackPath = '';
      lastFailureAtMs = 0;
      lastError = '';
      return makeStatus('connected');
    }

    if (!cdpEnabled) {
      return makeStatus('disabled');
    }

    const detected = detectImpl({
      platform,
      dataDir,
      desktopDir,
      applicationsDir,
      port: p,
    });

    if (detected?.manualOnly) {
      return makeStatus('manual_only', {
        manualCommand: detected.manualCommand || `antigravity --remote-debugging-port=${p}`,
      });
    }

    // If desktop shortcut creation fell back to a dataDir launcher/cmd during this
    // same outage and that file still exists, avoid regenerating in a 3s poll loop.
    const fallbackStillExists =
      autoRegeneratedInOutage &&
      Boolean(generatedFallbackPath) &&
      (() => {
        try {
          return fs.existsSync(generatedFallbackPath);
        } catch {
          return false;
        }
      })();

    if (detected?.exists || fallbackStillExists) {
      const keepAutoState = autoRegeneratedInOutage;
      return makeStatus(keepAutoState ? 'auto_regenerated' : 'existing', {
        autoGenerated: keepAutoState,
        launcherPath:
          (detected?.exists ? detected.launcherPath : generatedFallbackPath) ||
          extractPrimaryLauncherPath(lastGeneratedInfo),
        desktopShortcutPath:
          detected?.desktopShortcutPath || lastGeneratedInfo?.desktopShortcutPath || '',
        manualCommand: detected?.manualCommand || lastGeneratedInfo?.manualCommand || '',
      });
    }

    // Launcher is missing/deleted: automatically regenerate it once (with failure cooldown)
    if (lastFailureAtMs > 0 && now() - lastFailureAtMs < FAILURE_COOLDOWN_MS) {
      return makeStatus('generate_failed', {
        manualCommand: detected?.manualCommand || '',
        error: lastError || '自动生成启动器失败，请稍后重试',
      });
    }

    const res = await runGenerate(p, 'auto_regenerated');
    return makeStatus(res.status, {
      autoGenerated: res.autoGenerated,
      launcherPath: res.launcherPath,
      desktopShortcutPath: res.desktopShortcutPath,
      manualCommand: res.manualCommand || detected?.manualCommand || '',
      error: res.error,
    });
  }

  async function forceRegenerate({ port = DEFAULT_CDP_PORT } = {}) {
    lastFailureAtMs = 0;
    const p = Number(port) || DEFAULT_CDP_PORT;
    return runGenerate(p, 'auto_regenerated');
  }

  return {
    reconcile,
    forceRegenerate,
    getLastGeneratedInfo: () => lastGeneratedInfo,
  };
}
